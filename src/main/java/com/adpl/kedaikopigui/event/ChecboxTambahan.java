    private String formatRupiah(int nominal){
        return "Rp."+ String.format(java.util.Locale.forLanguageTag("id-ID"),"%,d", nominal);
    } 
    
    private void hitungTotal() {
    int total = 25000;
    
        if (cbAren.isSelected()) {
            total += 3000;
        }if (cbOat.isSelected()) {
            total += 5000;
        }if (cbExtra.isSelected()) {
            total += 4000;
        }
        
        lblTtlHarga.setText(formatRupiah(total));
  }

